import crypto from 'node:crypto';

export function generateCycloneDX(meta, components) {
  const timestamp = new Date().toISOString();
  const rootPurl = `pkg:generic/${encodeURIComponent(meta.productName || 'software-product')}@${meta.productVersion || '0.1.0'}`;

  return {
    $schema: 'http://cyclonedx.org/schema/bom-1.6.schema.json',
    bomFormat: 'CycloneDX',
    specVersion: '1.6',
    serialNumber: `urn:uuid:${crypto.randomUUID()}`,
    version: 1,
    metadata: {
      timestamp,
      tools: {
        components: [
          {
            type: 'application',
            name: 'craops',
            version: '0.4.0',
            publisher: 'CRAOps',
          },
        ],
      },
      component: {
        type: 'application',
        name: meta.productName || 'software-product',
        version: meta.productVersion || '0.1.0',
        purl: rootPurl,
        ...(meta.license ? { licenses: [{ license: { name: meta.license } }] } : {}),
      },
      properties: [
        { name: 'eu:cra:support_period_years', value: String(meta.supportYears || 5) },
        { name: 'eu:cra:conformity_module', value: 'Module A (Internal Control Self-Assessment Draft)' },
      ],
    },
    components: components.map((c) => ({
      type: 'library',
      'bom-ref': c.purl,
      name: c.name,
      version: c.version,
      purl: c.purl,
      scope: 'required',
      properties: [
        { name: 'cra:ecosystem', value: c.ecosystem },
        { name: 'cra:dependency_kind', value: c.direct ? 'direct' : 'transitive' },
      ],
    })),
  };
}

export function generateCsafVex(meta, vulnerabilities) {
  const now = new Date().toISOString();
  const productId = `${meta.productName || 'product'}-${meta.productVersion || '0.1.0'}`.replace(/[^A-Za-z0-9._-]/g, '-');

  return {
    document: {
      category: 'csaf_vex',
      csaf_version: '2.0',
      title: `EU CRA VEX Triage Dossier — ${meta.productName || 'Software Product'}`,
      publisher: {
        category: 'vendor',
        name: meta.productName || 'Vendor Name Required',
        namespace: 'https://craops.dev',
      },
      tracking: {
        current_release_date: now,
        id: `CRA-VEX-${now.slice(0, 10)}`,
        initial_release_date: now,
        revision_history: [
          {
            date: now,
            number: '1',
            summary: 'Initial automated VEX baseline generated by cra-audit for EU CRA Article 14 triage.',
          },
        ],
        status: 'draft',
        version: '1',
      },
    },
    product_tree: {
      full_product_names: [
        {
          name: `${meta.productName || 'Product'} ${meta.productVersion || '0.1.0'}`,
          product_id: productId,
        },
      ],
    },
    vulnerabilities: vulnerabilities.map((v) => ({
      cve: v.cve || undefined,
      ids: [{ system_name: 'OSV', text: v.id }],
      notes: [
        {
          category: 'description',
          text: `${v.packageName}@${v.packageVersion} (${v.ecosystem}): ${v.summary}`,
        },
      ],
      product_status: {
        under_investigation: [productId],
      },
      references: (v.references || []).map((url) => ({ summary: 'OSV Advisory', url })),
      threats: [
        {
          category: 'impact',
          details: `Severity=${v.severity}. Assess active exploitation status immediately for 24-hour ENISA SRP Article 14 reporting window.`,
        },
      ],
    })),
  };
}
