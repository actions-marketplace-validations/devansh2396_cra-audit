export function generateEnisaSrpTemplate(meta, osv) {
  return {
    schema: 'craops.enisa-srp-dossier.v1',
    portalUrl: 'https://portal.cra-srp.enisa.europa.eu',
    legalBasis: 'Regulation (EU) 2024/2847 Article 14 (Enforceable since 2026-09-11)',
    manufacturer: {
      legalName: '[Manufacturer Legal Name]',
      securityContactEmail: meta.securityEmail || '[security@company.com]',
      productName: meta.productName,
      affectedVersions: [meta.productVersion],
    },
    deadlines: {
      stage1_early_warning_hours: 24,
      stage2_vulnerability_or_incident_notification_hours: 72,
      stage3_final_report_vulnerability_days_after_mitigation: 14,
      stage3_final_report_incident_months: 1,
    },
    draftPayload: {
      notificationType: 'ACTIVELY_EXPLOITED_VULNERABILITY',
      awarenessTimestampUtc: new Date().toISOString(),
      memberStatesAffected: ['EU-WIDE (Verify Distribution Footprint)'],
      isCrossBorderImpact: true,
      suspectedMaliciousOrUnlawfulAct: 'UNKNOWN_UNDER_TRIAGE',
      cisaKevHitsCount: osv.summary.kev || 0,
      candidateCvesDetectedInScan: osv.vulnerabilities
        .filter((v) => v.isCisaKev || v.severity === 'CRITICAL' || v.severity === 'HIGH')
        .slice(0, 10)
        .map((v) => ({
          id: v.id,
          cve: v.cve,
          isCisaKev: Boolean(v.isCisaKev),
          package: `${v.packageName}@${v.packageVersion}`,
          severity: v.severity,
        })),
      correctiveMitigationSummary: '[Describe patch version, workaround, and customer notification channel]',
    },
  };
}
