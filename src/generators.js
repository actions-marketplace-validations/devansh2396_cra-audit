export function renderCraReportMarkdown(scan) {
  const { meta, components, osv, scoring } = scan;
  const topVulns = osv.vulnerabilities.slice(0, 15);
  return `# EU Cyber Resilience Act (CRA) Readiness Report — ${meta.productName}

- **Generated:** ${new Date().toISOString()}
- **CRA Readiness Score:** **${scoring.score} / 100** (Grade ${scoring.grade} — ${scoring.readinessLevel})
- **Parsed Components:** ${components.length} across [${meta.manifests.join(', ') || 'None detected'}]
- **Lockfiles Present:** ${meta.lockfiles.length > 0 ? meta.lockfiles.join(', ') : 'None (Gap)'}
- **OSV Known Vulnerabilities:** ${osv.offline ? 'Skipped (--offline)' : `${osv.summary.total} (CISA KEV Active-Exploit Hits: ${osv.summary.kev || 0}, Critical: ${osv.summary.critical}, High: ${osv.summary.high}, Medium: ${osv.summary.medium}, Low: ${osv.summary.low})`}
- **Article 14 ENISA SRP Status (Live Sept 11, 2026):** ${scoring.article14Status}

> **Engineering Notice:** This report is generated by \`cra-audit\` (CRAOps) to automate EU CRA technical evidence preparation. It is engineering compliance tooling and does not constitute formal legal advice or a Notified Body assessment.

---

## 1. Score Breakdown
| Compliance Domain | Score | Max |
| :--- | :---: | :---: |
${scoring.breakdown.map((b) => `| ${b.area} | ${b.score} | ${b.max} |`).join('\n')}

## 2. Annex I Security & Article 14 VDP Gaps
${scoring.annexIGaps.length === 0 ? '- No automated Annex I/Art. 14 baseline gaps detected.' : scoring.annexIGaps.map((g) => `- [ ] ${g}`).join('\n')}

## 3. Annex VII Technical File & Support Gaps
${scoring.annexVIIGaps.length === 0 ? '- No automated Annex VII baseline gaps detected.' : scoring.annexVIIGaps.map((g) => `- [ ] ${g}`).join('\n')}

## 4. Top Vulnerability Findings (For CSAF VEX & CISA KEV Triage)
${
  topVulns.length === 0
    ? '- None surfaced in this scan.'
    : topVulns
        .map(
          (v) =>
            `- **${v.id}**${v.cve ? ` (${v.cve})` : ''}${v.isCisaKev ? ' **[CISA KEV ACTIVE EXPLOIT]**' : ''} [${v.severity}] in \`${v.packageName}@${v.packageVersion}\`: ${v.summary}`,
        )
        .join('\n')
}
`;
}

